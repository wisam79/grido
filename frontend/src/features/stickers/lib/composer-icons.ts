const ICON_BY_ID = new Map(COMPOSER_ICONS.map((ic) => [ic.id, ic]));

export function renderComposerIconMarkup(
  iconId: string,
  cx: number,
  cy: number,
  size: number,
  monoColor: string,
): { markup: string; multiColor: boolean } {
  const icon = ICON_BY_ID.get(iconId) ?? COMPOSER_ICONS[0];
  const scale = Math.min(size / icon.width, size / icon.height);
  const x = cx - (icon.width * scale) / 2;
  const y = cy - (icon.height * scale) / 2;
  const colorAttr = icon.multiColor ? '' : ` fill="${monoColor}" color="${monoColor}"`;
  return {
    multiColor: icon.multiColor,
    markup: `<g transform="translate(${x.toFixed(2)} ${y.toFixed(2)}) scale(${scale.toFixed(4)})"${colorAttr}>${icon.body}</g>`,
  };
}
